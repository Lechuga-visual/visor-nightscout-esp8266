"""Build-time translations. User names, secrets and runtime markup are never rewritten."""
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = json.loads((ROOT / 'translations/en.json').read_text())
PATTERN = re.compile('|'.join(re.escape(key) for key in sorted(CATALOG, key=len, reverse=True)))
CPP_LITERAL = re.compile(r'\b(?:F|L|PSTR)\(\s*((?:"(?:\\.|[^"\\])*"\s*)+)\)')
# The checked-in scripts contain no quotes inside regular-expression literals.
# Comments are consumed first so apostrophes in comments cannot swallow code.
JS_TOKEN = re.compile(r'''//[^\n]*|/\*[\s\S]*?\*/|'(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*"|`(?:\\.|[^`\\])*`''')


def translate(text):
    return PATTERN.sub(lambda match: CATALOG[match[0]], text)


def javascript(text):
    def token(match):
        value = match[0]
        if value.startswith('/'):
            return value
        if value.startswith('`'):
            return '`' + translate(value[1:-1]) + '`'
        decoded = ast.literal_eval(value)
        translated = translate(decoded)
        return json.dumps(translated, ensure_ascii=False) if translated != decoded else value
    return JS_TOKEN.sub(token, text).replace("toLocaleTimeString('es',", "toLocaleTimeString('en',")


def literal(match):
    return ''.join(ast.literal_eval(value) for value in re.findall(r'"(?:\\.|[^"\\])*"', match[1]))


def hash_text(text):
    result = 2166136261
    for byte in text.encode():
        result = ((result ^ byte) * 16777619) & 0xffffffff
    return result


def header():
    source = (ROOT / 'src/main.cpp').read_text()
    translations = {literal(m): translate(literal(m)) for m in CPP_LITERAL.finditer(source)}
    translations = {a:b for a,b in translations.items() if a != b}
    # Canonical internal statuses stay in Spanish. Only their user-facing copies
    # are translated, so network/recovery comparisons keep their original meaning.
    status = [
        'Iniciando','Hora del navegador','Servidor cambiado','Memoria baja para lectura',
        'Sin memoria para historial','Sin memoria para JSON','Respuesta incompleta','Lectura no valida',
        'Error en cuerpo HTTP','Servidor sin lecturas','Token requiere HTTPS','Consultando servidor',
        'Sin memoria para TLS','Clave publica invalida','CA propia invalida','URL HTTPS invalida',
        'URL HTTP invalida','Esperando lectura','Codificacion HTTP no admitida','Error al crear Wi-Fi',
        'Configuracion inicial','Lectura; historial parcial','Conectado','Esperando hora NTP',
        'Sin hora: abre la web','Error de conexion','Conectando Wi-Fi','Sin Wi-Fi',
        'Estable','Subiendo','Subiendo rápido','Bajando','Bajando rápido','Sin tendencia']
    for value in status:
        assert translate(value) != value, value
        translations[value] = translate(value)
    hashes = {}
    for value in translations:
        hashed = hash_text(value)
        assert hashed not in hashes, f'Hash collision: {value} / {hashes.get(hashed)}'
        hashes[hashed] = value
    rows = sorted(translations.items())
    lines = ['// Generated by tools/embed_web_assets.py; edit translations/en.json.', '#pragma once',
             '#include <stdint.h>', '#ifdef ARDUINO', '#include <pgmspace.h>',
             '#else', '#define PROGMEM', '#define pgm_read_byte(p) (*(const unsigned char*)(p))',
             '#endif', 'namespace ui_translation {']
    for i,(es,en) in enumerate(rows):
        lines.append(f'const char en_{i}[] PROGMEM = {json.dumps(en, ensure_ascii=False)};')
    lines += ['inline const char* text(const char* source, bool english) {',
              '  if (!english) return source;',
              '  uint32_t hash = 2166136261u;',
              '  for (const char* p = source; pgm_read_byte(p); ++p) hash = (hash ^ pgm_read_byte(p)) * 16777619u;',
              '  switch (hash) {']
    for i,(es,_) in enumerate(rows):
        lines.append(f'    case 0x{hash_text(es):08x}u: return en_{i};')
    lines += ['    default: return source;', '  }', '}', '}  // namespace ui_translation']
    return '\n'.join(lines) + '\n'
