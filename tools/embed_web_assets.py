#!/usr/bin/env python3
"""Deterministically embed offline web assets as gzip in ESP8266 flash."""
import gzip
import re
try:
    from tools.localization import translate, javascript, header
except ModuleNotFoundError:
    from localization import translate, javascript, header
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def english_assets():
    result = {}
    for name in ('index.html', 'app.js', 'appearance.js', 'setup.js', 'night.js', 'setup.html'):
        source = (ROOT / 'web' / name).read_text(encoding='utf-8')
        result[name] = javascript(source) if name.endswith('.js') else translate(source)
    return result


def square_dashboard(source):
    source = source.replace('id="dial" viewBox', 'id="dial" data-shape="square" viewBox', 1)
    source = re.sub(r'<option value="0">[^<]*</option>', '', source, count=1)
    start = source.index('<g id="history-group">')
    end = source.index('<rect class="age-background"', start)
    source = source[:start] + source[end:]
    return re.sub(r'(<span id="view-scope">)[^<]*', r'\1', source, count=1)


def square_dashboard_script(source):
    start = source.index('  function drawGraph(')
    end = source.index('  function render()', start)
    source = source[:start] + source[end:]
    source = source.replace("    const history = $('history-group');\n    if (history) history.style.display = selected===0 ? '' : 'none';\n", '')
    source = source.replace("      if ($('history-group')) drawGraph(data.plot, square);\n", '')
    source = source.replace("($('history-group') ? 0 : 1)", '1')
    return re.sub(r"(text\('view-scope',\[)[^,]+,", r"\1'',", source, count=1)


def add_gzip(lines, symbol, source):
    data = gzip.compress(source.encode(), compresslevel=9, mtime=0)
    lines.append(f'const unsigned char {symbol}[] PROGMEM = {{')
    lines.extend('  ' + ', '.join(f'0x{b:02x}' for b in data[i:i+16]) + ',' for i in range(0,len(data),16))
    lines.append('};')


def add_asset(lines, name, symbol, source):
    transform = {'index.html': square_dashboard, 'app.js': square_dashboard_script}.get(name)
    if transform:
        lines.append('#ifdef SD_PRO_SQUARE_DISPLAY')
        add_gzip(lines, symbol, transform(source))
        lines.append('#else')
    add_gzip(lines, symbol, source)
    if transform:
        lines.append('#endif')


def generate():
    lines = ['// Generated by tools/embed_web_assets.py; do not edit.', '#pragma once',
             '#include <Arduino.h>', 'namespace web_assets {']
    for name in ('index.html', 'ui.css', 'app.js', 'appearance.js', 'setup.js', 'night.js'):
        add_asset(lines, name, name.replace('.', '_'), (ROOT / 'web' / name).read_text(encoding='utf-8'))
    for name, source in english_assets().items():
        if name != 'setup.html':
            add_asset(lines, name, 'en_' + name.replace('.', '_'), source)
    template = (ROOT / 'web/setup.html').read_text(encoding='utf-8')
    placeholders = re.findall(r'{{([a-z_]+)}}', template)
    assert placeholders == ['back_link', 'context', 'language_form', 'ssid', 'server_fields', 'username', 'csrf']
    for i, fragment in enumerate(re.split(r'{{[a-z_]+}}', template)):
        assert ')NSSETUP"' not in fragment
        lines.append(f'const char setup_html_{i}[] PROGMEM = R"NSSETUP({fragment})NSSETUP";')
    english_template = translate(template)
    for i, fragment in enumerate(re.split(r'{{[a-z_]+}}', english_template)):
        assert ')NSSETUP"' not in fragment
        lines.append(f'const char en_setup_html_{i}[] PROGMEM = R"NSSETUP({fragment})NSSETUP";')
    lines.append('}  // namespace web_assets')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    target = ROOT / 'include/generated/web_assets.h'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(generate(), encoding='utf-8')
    (ROOT / 'include/generated/ui_translations.h').write_text(header(), encoding='utf-8')
    (ROOT / 'web/en').mkdir(exist_ok=True)
    for name, content in english_assets().items():
        (ROOT / 'web/en' / name).write_text(content, encoding='utf-8')
    print('Embedded web assets:', target.relative_to(ROOT))
