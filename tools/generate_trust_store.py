#!/usr/bin/env python3
"""Refresh the checked-in public CA store from an explicitly pinned certifi bundle.

Maintainer dependency: certifi==2026.10.19, cryptography==50.0.2.
Normal firmware compilation uses the generated file and needs neither package.
"""

import hashlib
import json
from pathlib import Path


def encode_store(certificates, label):
    from cryptography import x509
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ec, rsa

    entries = []
    subjects = set()
    for certificate in certificates:
        key = certificate.public_key()
        if not isinstance(key, (rsa.RSAPublicKey, ec.EllipticCurvePublicKey)):
            raise ValueError("Unsupported root key algorithm")
        if isinstance(key, ec.EllipticCurvePublicKey) and key.curve.name not in ("secp256r1", "secp384r1", "secp521r1"):
            raise ValueError("Unsupported root curve")
        if not certificate.extensions.get_extension_for_class(x509.BasicConstraints).value.ca:
            raise ValueError("Only CA certificates belong in a trust store")
        digest = hashlib.sha256(certificate.subject.public_bytes()).digest()
        if digest in subjects:
            raise ValueError("Duplicate subject DN: dynamic trust lookup would be ambiguous")
        subjects.add(digest)
        entries.append((digest, certificate.public_bytes(serialization.Encoding.DER)))
    entries.sort(key=lambda entry: entry[0])
    blob = bytearray()
    index = []
    for digest, der in entries:
        index.append((digest, len(blob), len(der)))
        blob.extend(der)
    lines = [
        "// Generated by tools/generate_trust_store.py; do not edit by hand.",
        "// Public CA data: " + label + "; see certs/LICENSE-certifi and certs/README.md.",
        "#pragma once", "#include <stddef.h>", "#include <stdint.h>",
        "#ifndef PROGMEM", "#define PROGMEM", "#endif",
        "namespace public_ca_data {",
        "struct Entry { uint8_t subjectHash[32]; uint32_t offset; uint32_t length; };",
        "static const uint8_t certificates[] PROGMEM = {",
    ]
    for offset in range(0, len(blob), 16):
        lines.append("  " + ", ".join(f"0x{byte:02x}" for byte in blob[offset:offset + 16]) + ",")
    lines.extend(["};", "static const Entry index[] PROGMEM = {"])
    for digest, offset, length in index:
        lines.append("  {{" + ", ".join(f"0x{byte:02x}" for byte in digest) + "}, " + str(offset) + ", " + str(length) + "},")
    lines.extend(["};", f"static constexpr size_t count = {len(index)};", "}  // namespace public_ca_data", ""])
    return "\n".join(lines), {"source": label, "count": len(index), "der_bytes": len(blob), "der_sha256": hashlib.sha256(blob).hexdigest()}


def main():
    import certifi
    from cryptography import x509
    from importlib.metadata import distribution

    if certifi.__version__ != "2026.10.19":
        raise SystemExit("Install certifi==2026.10.19 before refreshing the public bundle")
    root = Path(__file__).resolve().parents[1]
    bundle = Path(certifi.where()).read_bytes()
    generated, metadata = encode_store(x509.load_pem_x509_certificates(bundle), "certifi " + certifi.__version__)
    metadata["pem_sha256"] = hashlib.sha256(bundle).hexdigest()
    (root / "src/generated").mkdir(parents=True, exist_ok=True)
    (root / "certs").mkdir(parents=True, exist_ok=True)
    (root / "src/generated/public_ca_data.h").write_text(generated)
    (root / "certs/manifest.json").write_text(json.dumps(metadata, indent=2) + "\n")
    package = distribution("certifi")
    license_path = next(path for path in package.files if str(path).endswith("/licenses/LICENSE"))
    (root / "certs/LICENSE-certifi").write_bytes(package.locate_file(license_path).read_bytes())
    print(f"Generated {metadata['count']} public roots, {metadata['der_bytes']} DER bytes")


if __name__ == "__main__":
    main()
